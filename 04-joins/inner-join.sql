SELECT
	CONTENTS,
	URL
FROM
	PHOTOS
	JOIN "comments" ON PHOTOS.ID = COMMENTS.PHOTO_ID;   

--3
SELECT
	P.ID AS PHOTOSID,
	COMMENTS.ID AS COMMENTSID
FROM
	PHOTOS AS P
	JOIN COMMENTS ON COMMENTS.PHOTO_ID = P.ID;

--4 where
SELECT
	URL,
	CONTENTS,
	PHOTOS.ID,
	COMMENTS.ID,
	PHOTOS.USER_ID,
	COMMENTS.USER_ID
FROM
	COMMENTS
	JOIN PHOTOS ON PHOTOS.ID = "comments".PHOTOS_ID
WHERE
	COMMENTS.USER_ID = PHOTOS.USER_ID;
